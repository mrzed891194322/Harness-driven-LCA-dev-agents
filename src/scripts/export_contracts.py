"""Export the SessionLaunchSpec contract (Python source) to JSON Schema and TypeScript.

    uv run --project src python src/scripts/export_contracts.py          # write files
    uv run --project src python src/scripts/export_contracts.py --check  # exit 1 when committed files drift
"""
from __future__ import annotations

import dataclasses
import json
import sys
import typing
from pathlib import Path
from typing import Any, Literal, get_args, get_origin, get_type_hints

SRC = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SRC))

from backend.core.contracts import session_launch_spec as contract  # noqa: E402

SCHEMA_PATH = SRC / "backend/core/contracts/session_launch_spec.schema.json"
TS_PATH = SRC / "pi-runtime/src/spec.generated.ts"
ROOT = contract.SessionLaunchSpec
HEADER = "Generated by src/scripts/export_contracts.py from backend/core/contracts/session_launch_spec.py. Do not edit."


def _is_typeddict(tp: Any) -> bool:
    return isinstance(tp, type) and issubclass(tp, dict) and hasattr(tp, "__annotations__") and hasattr(tp, "__total__")


def _struct_fields(tp: Any) -> list[tuple[str, Any, bool]]:
    hints = get_type_hints(tp)
    if dataclasses.is_dataclass(tp):
        out = []
        for f in dataclasses.fields(tp):
            required = f.default is dataclasses.MISSING and f.default_factory is dataclasses.MISSING
            out.append((f.name, hints[f.name], required or f.name == "schema_version"))
        if tp is ROOT:  # schema_version first, as on the wire
            out.sort(key=lambda x: x[0] != "schema_version")
        return out
    return [(name, hints[name], name in tp.__required_keys__) for name in tp.__annotations__]


def _structs() -> list[Any]:
    seen: list[Any] = []

    def visit(tp: Any) -> None:
        if dataclasses.is_dataclass(tp) or _is_typeddict(tp):
            if tp in seen:
                return
            seen.append(tp)
            for _, ftp, _ in _struct_fields(tp):
                visit(ftp)
        for arg in get_args(tp):
            visit(arg)

    visit(ROOT)
    return seen


def _schema(tp: Any) -> dict[str, Any]:
    origin = get_origin(tp)
    if tp is str:
        return {"type": "string"}
    if tp is bool:
        return {"type": "boolean"}
    if tp is int:
        return {"type": "integer"}
    if tp is Any:
        return {}
    if origin is Literal:
        vals = list(get_args(tp))
        return {"const": vals[0]} if len(vals) == 1 else {"enum": vals}
    if origin is list:
        return {"type": "array", "items": _schema(get_args(tp)[0])}
    if origin is dict:
        return {"type": "object", "additionalProperties": _schema(get_args(tp)[1]) or True}
    if dataclasses.is_dataclass(tp) or _is_typeddict(tp):
        return {"$ref": f"#/$defs/{tp.__name__}"}
    raise TypeError(f"unsupported contract type: {tp!r}")


def _object(tp: Any) -> dict[str, Any]:
    fields = _struct_fields(tp)
    return {"type": "object", "additionalProperties": False,
            "required": [n for n, _, req in fields if req],
            "properties": {n: _schema(t) for n, t, _ in fields}}


def json_schema() -> dict[str, Any]:
    return {"$schema": "https://json-schema.org/draft/2020-12/schema",
            "$id": "https://harness.local/src/backend/core/contracts/session_launch_spec.schema.json",
            "title": ROOT.__name__, "description": HEADER, **_object(ROOT),
            "$defs": {tp.__name__: _object(tp) for tp in _structs() if tp is not ROOT}}


def _ts(tp: Any) -> str:
    origin = get_origin(tp)
    if tp is str:
        return "string"
    if tp is bool:
        return "boolean"
    if tp is int:
        return "number"
    if tp is Any:
        return "unknown"
    if origin is Literal:
        return " | ".join(json.dumps(v) for v in get_args(tp))
    if origin is list:
        inner = _ts(get_args(tp)[0])
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if origin is dict:
        return f"Record<string, {_ts(get_args(tp)[1])}>"
    if dataclasses.is_dataclass(tp) or _is_typeddict(tp):
        return tp.__name__
    if origin is typing.Union:
        return " | ".join(_ts(a) for a in get_args(tp))
    raise TypeError(f"unsupported contract type: {tp!r}")


def typescript() -> str:
    lines = [f"/** {HEADER} */", "", f"export const SCHEMA_VERSION = {contract.SCHEMA_VERSION} as const;", ""]
    for tp in _structs():
        lines.append(f"export interface {tp.__name__} {{")
        for name, ftp, req in _struct_fields(tp):
            lines.append(f"  {name}{'' if req else '?'}: {_ts(ftp)};")
        lines += ["}", ""]
    schema = json.dumps(json_schema(), ensure_ascii=False, indent=2)
    lines += ["/** JSON Schema of SessionLaunchSpec (same as session_launch_spec.schema.json). */",
              f"export const LAUNCH_SPEC_SCHEMA = {schema} as const;", ""]
    return "\n".join(lines)


def outputs() -> dict[Path, str]:
    return {SCHEMA_PATH: json.dumps(json_schema(), ensure_ascii=False, indent=2) + "\n", TS_PATH: typescript()}


def main(argv: list[str]) -> int:
    drift = [p for p, text in outputs().items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
    if "--check" in argv:
        for p in drift:
            print(f"drift: {p.relative_to(SRC)} (run src/scripts/export_contracts.py)")
        return 1 if drift else 0
    for p, text in outputs().items():
        p.write_text(text, encoding="utf-8")
        print(f"wrote {p.relative_to(SRC)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
